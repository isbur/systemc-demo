// ═══════════════════════════════════════════════════════════════════════
//  C++ модуль для SystemC Constructor — D-триггер с асинхронным сбросом
//  Индексы входов:  in0 = clk,  in1 = d,  in2 = rst_n (активный низкий)
//  Индексы выходов: out0 = q
//  state[0] хранит защёлкнутое значение
// ═══════════════════════════════════════════════════════════════════════

// Комбинаторная часть — вызывается при каждом дельта-цикле.
// На выход подаём текущее защёлкнутое значение триггера.
void user_evaluate(int32_t* inputs, int32_t* outputs, int32_t* state) {
    outputs[0] = state[0];
}

// Фронт тактового сигнала. edge == 1 — положительный фронт, edge == 0 — отрицательный.
void user_clock_edge(int32_t edge, int32_t* inputs, int32_t* outputs, int32_t* state) {
    if (edge != 1) return;          // работаем только по положительному фронту

    if (inputs[2] == 0) {           // rst_n = 0 → активный сброс
        state[0] = 0;
    } else {                        // иначе — защёлкиваем D
        state[0] = inputs[1];
    }
    outputs[0] = state[0];
}

// Сброс схемы — сбрасываем внутреннее состояние.
void user_reset(int32_t* state) {
    state[0] = 0;
}